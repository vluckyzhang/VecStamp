"""Build the ASCII-only VBA module that the installer imports.

Also fills the generated block at the end of the module with the VSDX
template parts from src/vsdx (functions VsdxPart / VsdxMap) and the
XPS -> SVG converter src/helpers/xps2svg.ps1 (function HelperScript).

VBA imports .bas files in the system ANSI code page, so Chinese text in
string literals would break on non-Chinese Windows locales. This script
rewrites every string literal that contains non-ASCII characters as
U("hex"), where U() (defined in the module) decodes 4-digit UTF-16 hex
groups at run time. Comments must be ASCII.

Usage: python build/build_bas.py src/VecStamp.bas dist/VecStamp.bas
"""
import os
import sys


def encode_line(line, lineno):
    out, i, n = [], 0, len(line)
    while i < n:
        ch = line[i]
        if ch == "'":                      # comment to end of line
            rest = line[i:]
            if any(ord(c) > 127 for c in rest):
                raise SystemExit(f"line {lineno}: non-ASCII comment")
            out.append(rest)
            break
        if ch == '"':
            j, buf = i + 1, []
            while True:
                if j >= n:
                    raise SystemExit(f"line {lineno}: unterminated string")
                if line[j] == '"':
                    if j + 1 < n and line[j + 1] == '"':
                        buf.append('"'); j += 2; continue
                    break
                buf.append(line[j]); j += 1
            text = ''.join(buf)
            if any(ord(c) > 127 for c in text):
                data = text.encode('utf-16-le')
                hexs = ''.join(f'{int.from_bytes(data[k:k+2], "little"):04X}' for k in range(0, len(data), 2))
                out.append(f'U("{hexs}")')
            else:
                out.append(line[i:j + 1])
            i = j + 1
            continue
        if ord(ch) > 127:
            raise SystemExit(f"line {lineno}: non-ASCII outside string: {line!r}")
        out.append(ch)
        i += 1
    res = ''.join(out)
    if 'U("' in res and res.lstrip().lower().startswith(('const ', 'private const', 'public const')):
        raise SystemExit(f"line {lineno}: Const cannot use non-ASCII text")
    if len(res) > 1000:
        raise SystemExit(f"line {lineno}: line too long for VBA ({len(res)})")
    return res


ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VSDX_DIR = os.path.join(ROOT, 'src', 'vsdx')
HELPER = os.path.join(ROOT, 'src', 'helpers', 'xps2svg.ps1')
BEGIN = "' >>> GENERATED"
END = "' <<< GENERATED"


def vba_string_lines(text, var='s', width=180):
    out = []
    for i in range(0, len(text), width):
        chunk = text[i:i + width].replace('"', '""')
        out.append(f'            {var} = {var} & "{chunk}"' if i else f'            {var} = "{chunk}"')
    return out or [f'            {var} = ""']


def vsdx_block():
    entries = []
    for line in open(os.path.join(VSDX_DIR, 'map.txt'), encoding='utf-8'):
        if '=' in line:
            entries.append(line.strip().split('=', 1))
    code = [BEGIN + ': VSDX TEMPLATE PARTS AND HELPER SCRIPT (generated by build/build_bas.py - do not edit)',
            'Private Function VsdxPart(ByVal partName As String) As String',
            '    Dim s As String',
            '    Select Case partName']
    for src, _ in entries:
        text = open(os.path.join(VSDX_DIR, src), encoding='utf-8').read().replace('\r', '').replace('\n', '')
        if any(ord(c) > 127 for c in text):
            raise SystemExit(f'{src}: VSDX template parts must be ASCII')
        code.append(f'        Case "{src}"')
        code += vba_string_lines(text)
    code += ['    End Select', '    VsdxPart = s', 'End Function', '',
             'Private Function VsdxMap() As Variant']
    items = [f'"{a}={b}"' for a, b in entries]
    code.append('    VsdxMap = Array(' + ', _\n                    '.join(items) + ')')
    code += ['End Function', '']
    code += helper_block()
    code.append(END)
    return '\n'.join(code)


def helper_block(per_function=200):
    """HelperScript(): the PowerShell converter, line by line (split to stay below VBA's 64 KB per procedure)."""
    lines = open(HELPER, encoding='utf-8-sig').read().replace('\r', '').split('\n')
    if any(ord(c) > 127 for c in ''.join(lines)):
        raise SystemExit('src/helpers/xps2svg.ps1 must be ASCII')
    code, names = [], []
    for k in range(0, len(lines), per_function):
        name = 'HelperScript%d' % (len(names) + 1)
        names.append(name)
        code += ['Private Function %s() As String' % name, '    Dim s As String']
        for line in lines[k:k + per_function]:
            code.append('    s = s & "%s" & vbLf' % line.replace('"', '""'))
        code += ['    %s = s' % name, 'End Function', '']
    code += ['Private Function HelperScript() As String',
             '    HelperScript = ' + ' & '.join(n + '()' for n in names),
             'End Function']
    return code


def main(src, dst):
    text = open(src, encoding='utf-8-sig').read()
    if BEGIN in text:
        a = text.index(BEGIN)
        b = text.index(END, a) + len(END)
        text = text[:a] + vsdx_block() + text[b:]
    lines = text.splitlines()
    built = [encode_line(l, k + 1) for k, l in enumerate(lines)]
    data = '\r\n'.join(built) + '\r\n'
    data.encode('ascii')
    open(dst, 'w', encoding='ascii', newline='').write(data)
    print(f"wrote {dst}: {len(built)} lines")


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
